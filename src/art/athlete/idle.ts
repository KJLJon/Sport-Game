/**
 * @spec    001-initial-dev
 * @phase   13 — Visual overhaul: sprites and pseudo-3D
 * @task    T-13.3 — Athlete rendering: facings, run cycle, kit tint, and pattern
 * @story   US-2.3 — See the whole field on a small screen
 * @design  13-visual-overhaul.md §3.1 (athlete sheet), src/art/README.md (authoring format)
 * @invariant INV-4 (art is in-repo data, never a fetch)
 *
 * Purpose: the `idle` pose, all five authored facings (E, NE, N, S, SE), two frames each — a
 * standing frame and a one-pixel breath. West, north-west and south-west are never authored here;
 * `authoredFacing()` mirrors E, NE and SE for them at draw time (`src/art/README.md` §4), so every
 * kit marking on this file's `P`/`k` regions is kept left-right symmetric or a mirrored jersey
 * would read as flipped.
 *
 * Facings share one row layout so an athlete turning never bobs: rows 0-4 are margin, 5-18 the
 * head, 19-33 the torso, 34-47 the legs and feet, with the anchor (feet) on row 46 in every one.
 * South is the original T-13.2 frame, unchanged. North reuses South's torso and legs and recolours
 * the face to hair (no face from behind). East is a narrower profile (~14 px of shoulder against
 * South's ~20), split down the middle of the head into a hair back-half and a skin front-half, with
 * a leading leg (the trailing hip/thigh edge thinned and the whole lower body shifted toward the
 * front) and a forearm carried in front of the narrowed torso. North-east and south-east sit between
 * East and their neighbour: a slightly wider profile torso, a smaller leg/arm offset, and a head
 * split that leaves the sliver of face North-east's spec calls for versus the fuller face South-east
 * keeps.
 *
 * Read `src/art/README.md` before editing. In short: `.` is transparent, the body layer carries
 * the outline around the whole silhouette, and `K`/`k`/`P` on the kit layer are bound to the
 * team's colours when the atlas is built.
 */
