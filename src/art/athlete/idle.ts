/**
 * @spec    001-initial-dev
 * @phase   13 — Visual overhaul: sprites and pseudo-3D
 * @task    T-13.3 — Athlete rendering: facings, run cycle, kit tint, and pattern
 * @story   US-2.3 — See the whole field on a small screen
 * @design  13-visual-overhaul.md §3.1 (athlete sheet), src/art/README.md (authoring format)
 * @invariant INV-4 (art is in-repo data, never a fetch)
 *
 * Purpose: the `idle` pose, all five authored facings (E, NE, N, S, SE), two frames each — a
 * standing frame and a one-pixel breath. West, north-west and south-west are never authored here;
 * `authoredFacing()` mirrors E, NE and SE for them at draw time (`src/art/README.md` §4). On every
 * facing the whole jersey — torso and sleeves — is one `P` region, so `tint.ts` has geometry to
 * band into stripes, hoops or halves; `k` stays reserved for a thin collar/waistband trim and `K`
 * for the shorts only. `P`/`k` are placed symmetrically about each frame's own centre column, so a
 * mirrored jersey never reads as flipped.
 *
 * Facings share one row layout so an athlete turning never bobs: rows 0-4 are margin, 5-18 the
 * head, 19-33 the torso, 34-47 the legs and feet, with the anchor (feet) on row 46 in every one.
 * South's body layer is the original T-13.2 frame, unchanged — every other facing is proportioned
 * against it; only its kit layer's `K`→`P` conversion is new here. North reuses South's torso and
 * legs and recolours the face to hair (no face from behind). East, north-east and south-east are
 * profiles: the torso tapers in three steps from the shoulders to the waist (narrowest on East, at
 * ~12-16 px against South's ~20), the head splits down the middle into a hair back-half and a skin
 * front-half — a wide split on East, a sliver on north-east, most of the face kept on south-east —
 * and a forward forearm is fused straight into the torso's own fill on one middle band, so the
 * outline wraps the arm-and-torso union with no seam between them. Hips, legs and feet are never
 * offset sideways — only the trailing hip's outer edge is thinned by a pixel — so every facing's
 * lower body sits on the same centre line as its torso.
 *
 * Read `src/art/README.md` before editing. In short: `.` is transparent, the body layer carries
 * the outline around the whole silhouette, and `K`/`k`/`P` on the kit layer are bound to the
 * team's colours when the atlas is built.
 */
