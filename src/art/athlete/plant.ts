/**
 * @spec    001-initial-dev
 * @phase   13 — Visual overhaul: sprites and pseudo-3D
 * @task    T-13.3 — Athlete rendering: facings, run cycle, kit tint, and pattern
 * @story   US-2.3 — See the whole field on a small screen
 * @design  13-visual-overhaul.md §3.1 (athlete sheet), §5 (sport pose mappings), src/art/README.md
 * @invariant INV-4 (art is in-repo data, never a fetch)
 *
 * Purpose: the `plant` pose — the braced, wide-stance frame a sport reaches for when an athlete
 * stops hard, pivots, posts up, or shields the ball (`13` §5: basketball's pivot/post-up, soccer's
 * shielding). One held frame per authored facing (0, 1, 2, 6, 7); 3, 4, 5 are these mirrored at
 * draw time per `src/art/README.md` §4.
 *
 * The head, neck, and shoulder-cap rows are lifted verbatim from `idle.ts`'s south frame (just
 * shifted two rows down, per the brief's "head sits 2-4 px lower") so the athlete reads as the same
 * character across poses. Below the shoulders the pose diverges hard: feet plant wide on row 46,
 * knees flare outward at the widest point (row 34), and both arms swing out from the torso with a
 * visible transparent gap between arm and body — the thing that has to be true in silhouette alone
 * for this pose to read differently from `idle` at a glance.
 *
 * Facing 2 (N) reuses the south silhouette but replaces the face pixels with hair, since the back of
 * the head shows no face. Facings 1 (NE) and 7 (SE) share one body silhouette — the south stance with
 * its planted feet shifted two columns east, reading as a brace turned three-quarters — and differ
 * only in head treatment (7 keeps the face, 1 shows hair), matching how little a 3/4 turn changes a
 * wide low brace at this resolution. Facing 0 (E) is a genuine profile: narrower shoulders (14 px),
 * and the two feet no longer mirror each other but sit at different depths (near/far), each still
 * planted on row 46.
 */
